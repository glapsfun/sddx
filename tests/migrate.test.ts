import { describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { sha256 } from "../src/lib/receipt";
import { goalSpec, sddx, writeSpec } from "./helpers";
import { scenario } from "./scenario";
import { extractV5Fixture } from "./v5-fixture";

const git = (cwd: string, ...args: string[]) =>
  spawnSync("git", args, { cwd, encoding: "utf8" }).stdout.trim();

const status = (cwd: string) =>
  git(cwd, "status", "--porcelain", "--untracked-files=all", "--ignored");

/** The sddx 5 fixture with its in-flight RED task closed out, as sddx 5 would. */
function quietV5Repo(): { dir: string; redTaskId: string } {
  const { dir, ids } = extractV5Fixture();
  const path = join(
    dir,
    ".sddx-worktrees",
    ids.redTaskId,
    ".sddx",
    "tasks",
    `${ids.redTaskId}.json`,
  );
  const t = JSON.parse(readFileSync(path, "utf8"));
  t.phase = "ABANDONED";
  t.history.push({ phase: "ABANDONED", at: new Date().toISOString() });
  writeFileSync(path, `${JSON.stringify(t, null, 2)}\n`);
  return { dir, redTaskId: ids.redTaskId };
}

function receiptHashes(dir: string): Record<string, string> {
  const r = join(dir, ".sddx", "receipts");
  return Object.fromEntries(readdirSync(r).map((f) => [f, sha256(readFileSync(join(r, f)))]));
}

describe("refusing to run on sddx 5 state", () => {
  scenario("legacy-migration", "Plan check on a v5 repository", () => {
    const { dir } = extractV5Fixture();
    const spec = writeSpec(dir, "2026-01-01-new", goalSpec({ tasks: [{ id: "N1" }] }));
    const r = sddx(dir, "plan", "check", spec);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain("sddx 5 state");
    expect(r.stderr).toContain("sddx migrate");
  });

  scenario("legacy-migration", "Audit still works", () => {
    const { dir } = extractV5Fixture();
    const r = sddx(dir, "audit");
    expect(r.status).toBe(0);
    expect(r.stdout).toContain("chain intact");
  });
});

describe("diagnostics on sddx 5 state", () => {
  scenario("legacy-migration", "Config validation points at migrate", () => {
    const { dir } = extractV5Fixture();
    const r = sddx(dir, "config", "validate");
    expect(r.status).toBe(1);
    expect(r.stderr).toContain("written by sddx 5");
    expect(r.stderr).toContain("sddx migrate");
  });
});

describe("preview and refusal", () => {
  scenario("legacy-migration", "Preview writes nothing", () => {
    const { dir } = quietV5Repo();
    const before = status(dir);
    const r = sddx(dir, "migrate");
    expect(r.status).toBe(0);
    expect(r.stdout).toContain("remove  .claude/skills/sddx-run/SKILL.md");
    expect(r.stdout).toContain("preview only, nothing was written");
    expect(status(dir)).toBe(before);
  });

  scenario("legacy-migration", "Task in RED", () => {
    const { dir, ids } = extractV5Fixture();
    const before = status(dir);
    const r = sddx(dir, "migrate", "--yes");
    expect(r.status).toBe(1);
    expect(r.stderr).toContain(`task ${ids.redTaskId} is RED`);
    expect(status(dir)).toBe(before);
  });

  test("an unfinished v5 goal is named too", () => {
    const { dir, ids } = extractV5Fixture();
    const r = sddx(dir, "migrate");
    expect(r.stderr).toContain(`goal ${ids.goalId} has unfinished tasks: ${ids.redTaskId}`);
  });
});

describe("applying", () => {
  scenario("legacy-migration", "Unmodified generated skill removed", () => {
    const { dir } = quietV5Repo();
    expect(sddx(dir, "migrate", "--yes").status).toBe(0);
    expect(existsSync(join(dir, ".claude", "skills", "sddx-run", "SKILL.md"))).toBe(false);
    expect(existsSync(join(dir, ".sddx", "adapters", "claude.json"))).toBe(false);
  });

  test("ownership is proven from the frozen table when the local manifest is gone", () => {
    const { dir } = quietV5Repo();
    rmSync(join(dir, ".sddx", "local", "adapters"), { recursive: true, force: true });
    expect(sddx(dir, "migrate", "--yes").status).toBe(0);
    expect(existsSync(join(dir, ".claude", "agents", "sddx-orchestrator.md"))).toBe(false);
  });

  scenario("legacy-migration", "Edited generated file kept", () => {
    const { dir } = quietV5Repo();
    const planner = join(dir, ".claude", "agents", "sddx-planner.md");
    writeFileSync(planner, `${readFileSync(planner, "utf8")}\nLocal note.\n`);
    const r = sddx(dir, "migrate", "--yes");
    expect(r.status).toBe(0);
    expect(existsSync(planner)).toBe(true);
    expect(r.stdout).toContain(
      ".claude/agents/sddx-planner.md: generated by sddx 5 but edited since",
    );
  });

  scenario("legacy-migration", "User hooks preserved", () => {
    const { dir } = quietV5Repo();
    expect(sddx(dir, "migrate", "--yes").status).toBe(0);
    const settings = readFileSync(join(dir, ".claude", "settings.json"), "utf8");
    expect(settings).toContain("echo user-hook");
    expect(settings).toContain("Bash(ls:*)");
    expect(settings).not.toContain("sddx hook");
  });

  scenario("legacy-migration", "Config rewritten", () => {
    const { dir } = quietV5Repo();
    writeFileSync(
      join(dir, ".sddx", "config.json"),
      `${JSON.stringify({
        schema_version: "1.0",
        interaction_mode: "auto",
        runtime_scope: "project",
        package_manager: "npm",
        adapters: ["claude"],
        stuck_threshold: 4,
      })}\n`,
    );
    expect(sddx(dir, "migrate", "--yes").status).toBe(0);
    expect(JSON.parse(readFileSync(join(dir, ".sddx", "config.json"), "utf8"))).toEqual({
      schema_version: "2.0",
      interaction_mode: "auto",
      stuck_threshold: 4,
    });
  });

  scenario("legacy-migration", "Receipts untouched", () => {
    const { dir } = quietV5Repo();
    const before = receiptHashes(dir);
    const tokens = readdirSync(join(dir, ".sddx", "approvals"));
    const goalRefs = git(dir, "for-each-ref", "refs/sddx/goals/");
    expect(sddx(dir, "migrate", "--yes").status).toBe(0);
    expect(receiptHashes(dir)).toEqual(before);
    expect(readdirSync(join(dir, ".sddx", "approvals"))).toEqual(tokens);
    expect(git(dir, "for-each-ref", "refs/sddx/goals/")).toBe(goalRefs);
    expect(sddx(dir, "audit").status).toBe(0);
  });

  test("v5 task and spec files are archived under .sddx/legacy", () => {
    const { dir } = quietV5Repo();
    expect(sddx(dir, "migrate", "--yes").status).toBe(0);
    expect(readdirSync(join(dir, ".sddx", "legacy", "tasks"))).toEqual([
      "20261026-health-returns-ok.json",
    ]);
    expect(readdirSync(join(dir, ".sddx", "legacy", "specs"))).toEqual([
      "20261026-health-returns-ok.yaml",
    ]);
    expect(
      existsSync(join(dir, ".sddx", "legacy", "drafts", "2026-10-26-fixture-graph.yaml")),
    ).toBe(true);
    expect(existsSync(join(dir, ".sddx", "tasks", "20261026-health-returns-ok.json"))).toBe(false);
  });

  scenario("legacy-migration", "Project-pinned v5", () => {
    const { dir } = quietV5Repo();
    const pkg = `${JSON.stringify({ name: "app", devDependencies: { "@glapsfun/sddx": "^5.0.0" } }, null, 2)}\n`;
    writeFileSync(join(dir, "package.json"), pkg);
    const r = sddx(dir, "migrate", "--yes");
    expect(r.status).toBe(0);
    expect(readFileSync(join(dir, "package.json"), "utf8")).toBe(pkg);
    expect(r.stdout).toContain("lists @glapsfun/sddx; remove it or upgrade it to 6 yourself");
  });

  scenario("legacy-migration", "Second run", () => {
    const { dir } = quietV5Repo();
    expect(sddx(dir, "migrate", "--yes").status).toBe(0);
    const again = sddx(dir, "migrate", "--yes");
    expect(again.status).toBe(0);
    expect(again.stdout).toContain("nothing to do");
  });

  test("after migrating, v6 commands work on the repository", () => {
    const { dir } = quietV5Repo();
    expect(sddx(dir, "migrate", "--yes").status).toBe(0);
    const spec = writeSpec(dir, "2026-01-01-new", goalSpec({ tasks: [{ id: "N1" }] }));
    expect(sddx(dir, "plan", "check", spec).status).toBe(0);
    expect(sddx(dir, "doctor").stdout).toContain("PASS v5-leftovers");
  });
});
